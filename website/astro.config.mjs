// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import starlightLinksValidator from 'starlight-links-validator';

// Served from GitHub Pages at https://jimbuck.github.io/Ion/. Override with DOCS_SITE / DOCS_BASE for forks.
const site = process.env.DOCS_SITE ?? 'https://jimbuck.github.io';
const base = process.env.DOCS_BASE ?? '/Ion';

const section = (label, directory, collapsed = false) => ({ label, collapsed, items: [{ autogenerate: { directory } }] });
// Sections with nested groups list their top-level pages explicitly so the nested group gets a real label
// (an autogenerated subdirectory is labelled with its folder name).
const pages = (directory, slugs) => slugs.map((slug) => `${directory}/${slug}`);
const nested = (label, directory, top, groups) => ({
	label,
	items: [...pages(directory, top), ...groups.map(([groupLabel, sub]) => section(groupLabel, `${directory}/${sub}`))],
});

